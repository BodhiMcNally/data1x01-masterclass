import assert from 'node:assert/strict';
import { Room } from './room';
import { validateMessage, validateQuestion } from './validate';
import { definition } from '../deck/config';
import type { PollQuestion } from '../shared/protocol';

const presenter = {role:'deck' as const, voter:'test-presenter', presenter:true};
const a = {role:'audience' as const, voter:'a', presenter:false};
const b = {...a, voter:'b'};
const revision = {topic:'Q1: Study design',outcomes:[{id:'LO2',text:'Identify study design'}],resources:[{label:'Topic 1',url:'https://canvas.sydney.edu.au/courses/74355/pages/topic-1-introduction'}]};
const q: PollQuestion = {type:'poll',id:'vote-q1',prompt:'Practice',options:['A','B','C','D'],confidence:true,revision};
const room = Room.create('test-learning');
const apply = (sender: typeof a | typeof presenter, msg: any) => room.apply(sender,msg);
assert.equal(apply(presenter,{t:'open',question:q}).ok,true);
assert.equal(apply(a,{t:'confidence',id:q.id,choice:2}).ok,false,'confidence requires an answer');
assert.equal(apply(a,{t:'vote',id:q.id,choice:0}).ok,true);
assert.equal(apply(a,{t:'confidence',id:q.id,choice:2}).ok,true);
assert.equal(apply(b,{t:'vote',id:q.id,choice:1}).ok,true);
assert.equal(apply(b,{t:'confidence',id:q.id,choice:0}).ok,true);
assert.equal(room.audienceState().live!.results,null,'no class results before closure');
assert.equal(room.mine(a.voter).review,undefined,'no correctness before reveal');
assert.equal(room.mine(b.voter).confidence?.[q.id],0,'zero is preserved');
const reveal=apply(presenter,{t:'reveal',id:q.id,correct:[1]});
assert.equal(reveal.ok && reveal.allMineChanged,true,'all phones receive updated receipts after reveal');
const results=room.deckState(true,2).questions[q.id].results;
assert.equal(results.type,'poll');
if(results.type==='poll') {assert.deepEqual(results.confidence?.counts,[1,0,1]);assert.equal(results.confidence?.confidentlyIncorrect,1);}
assert.equal(room.mine('a').review![0].correct,false);
assert.equal(room.mine('b').review![0].correct,true);
assert.equal(room.mine('new-student').review![0].choice,null,'late joiners have no invented responses');
assert.equal(apply(a,{t:'confidence',id:q.id,choice:1}).ok,false,'cannot edit confidence after answer reveal');
const restored=Room.restore('test-learning',JSON.parse(JSON.stringify(room.dump())));
assert.deepEqual(restored.mine('a'),room.mine('a'),'receipts survive persistence/reconnect');
assert.deepEqual(restored.mine('b'),room.mine('b'));
assert.equal(Room.create('other-session').mine('a').review,undefined,'session isolation');
apply(presenter,{t:'reset',id:q.id});
assert.equal(room.mine('a').review,undefined);
assert.equal(room.mine('a').confidence,undefined);
apply(presenter,{t:'open',question:q});
apply(a,{t:'vote',id:q.id,choice:0});apply(a,{t:'confidence',id:q.id,choice:1});
apply(a,{t:'vote',id:q.id,choice:2});
assert.equal(room.mine('a').confidence,undefined,'changing the answer requires a fresh confidence rating');
assert.equal(validateMessage({t:'confidence',id:q.id,choice:3}).ok,false);
assert.equal(validateMessage({t:'confidence',id:q.id,choice:-1}).ok,false);
assert.equal(typeof validateQuestion({...q,revision:{...revision,resources:[{label:'bad',url:'javascript:alert(1)'}]}}),'string');
assert.equal(typeof validateQuestion({...q,revision:{...revision,resources:[{label:'bad',url:'https://evil.example/'}]}}),'string');
const clean=validateQuestion({...q,correct:[1]});
assert.equal(typeof clean,'object');assert.equal('correct' in (clean as object),false);
assert.deepEqual(definition({...q,results:'hidden',correct:[1]}),q,'deck sends revision metadata but never correct answers');
apply(presenter,{t:'reset'});assert.deepEqual(room.mine('a'),{votes:{},answers:{},ratings:{}});
console.log('Learning feature checks passed: confidence, privacy, reveal, receipts, reset, restore, URLs and session isolation.');

